#!/usr/bin/env node
// Generates ejs-unicode-tables.h: the code-point range tables behind
// \p{...} / \P{...} in regexps (see ejs-regexp.c's pattern translator).
//
// Host tooling, runs under node.  The data comes from the same npm
// packages mathiasbynens' test262 property-escapes generator uses, so
// the tables agree with the suite by construction:
//
//   @unicode/unicode-17.0.0                    code points per property
//   unicode-canonical-property-names-ecmascript  the ES property list
//   unicode-property-aliases-ecmascript          property-name aliases
//   unicode-match-property-value-ecmascript      value aliases (gc/sc/scx)
//
// The packages are deliberately NOT devDependencies — they are only
// needed to regenerate, and the output is checked in.  Regenerate with:
//
//   mkdir /tmp/ucd && cd /tmp/ucd && npm init -y && \
//     npm i @unicode/unicode-17.0.0 unicode-canonical-property-names-ecmascript \
//           unicode-property-aliases-ecmascript unicode-match-property-value-ecmascript
//   node runtime/gen-unicode-tables.mjs --data /tmp/ucd > runtime/ejs-unicode-tables.h
//
// Bumping test262's suite.sha across a Unicode release means bumping
// the data package version here in the same commit.

import { createRequire } from "node:module";
import * as path from "node:path";

const UNICODE_VERSION = "17.0.0";
const PKG = `@unicode/unicode-${UNICODE_VERSION}`;

const dataArg = process.argv.indexOf("--data");
const dataDir = dataArg >= 0 ? process.argv[dataArg + 1] : process.cwd();
const req = createRequire(path.join(path.resolve(dataDir), "noop.js"));

const index = req(PKG);
const canonicalNames = req("unicode-canonical-property-names-ecmascript"); // Set of ES property names
const propertyAliases = req("unicode-property-aliases-ecmascript"); // Map alias -> canonical
const valueAliases = req("unicode-match-property-value-ecmascript/data/mappings.js"); // Map prop -> Map(alias -> canonical)

const codePoints = (kind, name) => req(`${PKG}/${kind}/${name}/code-points.js`);

// ---- range compression ----
function toRanges(points) {
    const ranges = [];
    let start = -2, end = -2;
    for (const cp of points) {
        if (cp === end + 1) { end = cp; continue; }
        if (start >= 0) ranges.push([start, end]);
        start = end = cp;
    }
    if (start >= 0) ranges.push([start, end]);
    return ranges;
}

// ---- collect the four tables ----
// Every entry: { name, canonical } where canonical keys the shared
// range array.  Alias rows point at the canonical row's ranges.

// enumerated properties usable with '=': General_Category, Script,
// Script_Extensions (per UnicodeMatchProperty)
const ENUMERATED = ["General_Category", "Script", "Script_Extensions"];

// binary properties: the ES canonical list minus the enumerated three
const binaryCanonical = [...canonicalNames].filter((n) => !ENUMERATED.includes(n)).sort();
for (const b of binaryCanonical) {
    if (!index.Binary_Property.includes(b))
        throw new Error(`ES binary property ${b} missing from ${PKG} Binary_Property`);
}

const rangesByKey = new Map(); // "kind/Canonical" -> ranges
function ensureRanges(kind, canonical) {
    const key = `${kind}/${canonical}`;
    if (!rangesByKey.has(key)) rangesByKey.set(key, toRanges(codePoints(kind, canonical)));
    return key;
}

function aliasRows(kind, canonical, aliasMap) {
    // every spelling (canonical + aliases) that maps to this canonical value
    const rows = new Set([canonical]);
    for (const [alias, canon] of aliasMap) if (canon === canonical) rows.add(alias);
    return [...rows].map((name) => ({ name, key: ensureRanges(kind, canonical) }));
}

// lone names: binary properties (+ their aliases) and General_Category
// values (+ their aliases) — both resolvable without an '='
const gcAliasMap = valueAliases.get("General_Category");
const lone = [];
for (const b of binaryCanonical) {
    const rows = new Set([b]);
    for (const [alias, canon] of propertyAliases) if (canon === b) rows.add(alias);
    for (const name of rows) lone.push({ name, key: ensureRanges("Binary_Property", b) });
}
const gc = [];
for (const v of index.General_Category) {
    for (const row of aliasRows("General_Category", v, gcAliasMap)) {
        gc.push(row);
        lone.push(row); // \p{Lu} === \p{General_Category=Lu}
    }
}
const sc = [], scx = [];
const scAliasMap = valueAliases.get("Script");
for (const v of index.Script) sc.push(...aliasRows("Script", v, scAliasMap));
for (const v of index.Script_Extensions) scx.push(...aliasRows("Script_Extensions", v, scAliasMap));

// ---- emit ----
const out = [];
out.push(`/* Generated by gen-unicode-tables.mjs from ${PKG} — do not edit.`);
out.push(` * Unicode ${UNICODE_VERSION}; regenerate per the header of that script.`);
out.push(` */`);
out.push(`#ifndef _ejs_unicode_tables_h_`);
out.push(`#define _ejs_unicode_tables_h_`);
out.push(``);
out.push(`#include <stdint.h>`);
out.push(``);
out.push(`typedef struct { uint32_t start, end; } EJSUnicodeRange;`);
out.push(`typedef struct { const char *name; const EJSUnicodeRange *ranges; uint32_t nranges; } EJSUnicodeProperty;`);
out.push(``);

let totalRanges = 0;
const cIdent = new Map();
for (const [key, ranges] of rangesByKey) {
    const id = "_ejs_ucd_" + key.replace(/[^A-Za-z0-9]/g, "_");
    cIdent.set(key, id);
    totalRanges += ranges.length;
    const rows = ranges.map(([a, b]) => `{${a},${b}}`);
    out.push(`static const EJSUnicodeRange ${id}[] = { /* ${ranges.length} */`);
    for (let i = 0; i < rows.length; i += 8) out.push("    " + rows.slice(i, i + 8).join(",") + ",");
    out.push(`};`);
}
out.push(``);

function emitTable(cname, rows) {
    // sorted + deduped by name for bsearch; a duplicate spelling with a
    // different range set would be a data bug, so it throws
    const byName = new Map();
    for (const r of rows) {
        if (byName.has(r.name) && byName.get(r.name) !== r.key)
            throw new Error(`${cname}: conflicting entries for ${r.name}`);
        byName.set(r.name, r.key);
    }
    const sorted = [...byName.keys()].sort();
    out.push(`static const EJSUnicodeProperty ${cname}[] = {`);
    for (const name of sorted) {
        const key = byName.get(name);
        const id = cIdent.get(key);
        out.push(`    { "${name}", ${id}, ${rangesByKey.get(key).length} },`);
    }
    out.push(`};`);
    out.push(`static const uint32_t ${cname}_count = ${sorted.length};`);
    out.push(``);
    return sorted.length;
}

const nLone = emitTable("_ejs_unicode_lone_properties", lone);
const nGc = emitTable("_ejs_unicode_gc_values", gc);
const nSc = emitTable("_ejs_unicode_sc_values", sc);
const nScx = emitTable("_ejs_unicode_scx_values", scx);

out.push(`#endif /* _ejs_unicode_tables_h_ */`);
process.stdout.write(out.join("\n") + "\n");

console.error(
    `tables: lone ${nLone}, gc ${nGc}, sc ${nSc}, scx ${nScx}; ` +
    `${rangesByKey.size} range sets, ${totalRanges} ranges (${(totalRanges * 8 / 1024).toFixed(0)}KB)`
);
